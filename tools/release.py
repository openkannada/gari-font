"""Build the Gari release files.

    uv run python tools/release.py

writes dist/Gari/ (TTF, OTF, WOFF2, a Kannada subset for the web, a specimen, OFL.txt,
FONTLOG.txt and SHA256SUMS) and dist/Gari-<version>.zip with its checksum.

The TTF is what `make` builds (FontForge, then tools/finish.py). The OTF is generated by
FontForge from the same source and finished the same way.
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

sys.path.insert(0, str(Path(__file__).parent))
import finish  # noqa: E402
import specimen  # noqa: E402

ROOT = Path(__file__).parent.parent
SOURCE = ROOT / "Gari.sfd"
CREDIT = "Based on Navilu by Aravinda VK."
# Kannada, the joiners, the dotted circle and the dandas; the site sets Latin in another font.
WEB_UNICODES = [*range(0x0C80, 0x0D00), 0x200C, 0x200D, 0x25CC, 0x0964, 0x0965, 0x0020, 0x00A0]
DOCS = ("OFL.txt", "FONTLOG.txt")
GENERATE_OTF = "import fontforge, sys; fontforge.open(sys.argv[1]).generate(sys.argv[2])"


def build(work: Path) -> tuple[Path, Path]:
    """Gari.ttf from make, and an OTF from FontForge, both finished."""
    subprocess.run(["make"], cwd=ROOT, check=True)
    work.mkdir(parents=True, exist_ok=True)
    otf = work / "Gari.otf"
    subprocess.run(
        ["fontforge", "-lang=py", "-c", GENERATE_OTF, str(SOURCE), str(otf)],
        check=True,
        stderr=subprocess.DEVNULL,
    )
    finish.main([str(otf)])
    return ROOT / "Gari.ttf", otf


def placed(font_path: Path, folder: Path) -> Path:
    """Copy a font to folder under its PostScript name."""
    ps = TTFont(font_path)["name"].getDebugName(6)
    target = folder / f"{ps}{font_path.suffix}"
    folder.mkdir(parents=True, exist_ok=True)
    shutil.copy(font_path, target)
    return target


def woff2(font_path: Path, out_dir: Path) -> Path:
    font = TTFont(font_path)
    font.flavor = "woff2"
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / f"{font_path.stem}.woff2"
    font.save(target)
    return target


def web_subset(font_path: Path, out_dir: Path) -> Path:
    """The font cut to Kannada, as WOFF2 for the site."""
    font = TTFont(font_path)
    options = subset.Options()
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=WEB_UNICODES)
    subsetter.subset(font)
    family = font["name"].getDebugName(1).replace(" ", "")
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / f"{family}-Kannada.woff2"
    font.flavor = "woff2"
    font.save(target)
    return target


def checksums(folder: Path) -> Path:
    lines = [
        f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.relative_to(folder).as_posix()}"
        for p in sorted(folder.rglob("*"))
        if p.is_file() and p.name != "SHA256SUMS"
    ]
    target = folder / "SHA256SUMS"
    target.write_text("\n".join(lines) + "\n")
    return target


def archive(folder: Path, version: str) -> Path:
    target = folder.parent / f"{folder.name}-{version}.zip"
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(folder.rglob("*")):
            if p.is_file():
                z.write(p, p.relative_to(folder.parent).as_posix())
    digest = hashlib.sha256(target.read_bytes()).hexdigest()
    target.with_name(target.name + ".sha256").write_text(f"{digest}  {target.name}\n")
    return target


def version(font_path: Path) -> str:
    return TTFont(font_path)["name"].getDebugName(5).removeprefix("Version ").split(";")[0]


def release(work: Path, dist: Path) -> Path:
    ttf, otf = build(work)
    family = TTFont(ttf)["name"].getDebugName(1)
    out = dist / family.replace(" ", "")
    if out.exists():
        shutil.rmtree(out)
    static = placed(ttf, out / "ttf")
    placed(otf, out / "otf")
    woff2(static, out / "webfonts")
    web_subset(static, out / "web")
    for doc in DOCS:
        shutil.copy(ROOT / doc, out / doc)
    specimen.write(out, family, version(static), CREDIT, static)
    checksums(out)
    return archive(out, version(static))


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--work", type=Path, default=ROOT / "build" / "release")
    parser.add_argument("--dist", type=Path, default=ROOT / "dist")
    args = parser.parse_args(argv)
    print(release(args.work, args.dist))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
